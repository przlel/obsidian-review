#!/bin/bash
# Assembles the md-review plugin into dist/: vendored diff-match-patch + core + plugin.
# Usage: ./build.sh [vault]   With a vault folder, also installs the plugin into
# <vault>/.obsidian/plugins/md-review/ (reload the plugin in Obsidian afterwards).
set -euo pipefail
SRC="$(cd "$(dirname "$0")" && pwd)"
DIST="$SRC/dist"
# The vendored library is pinned: npm diff-match-patch 1.0.5, index.js, unchanged.
# The build stops when the file differs, so a changed copy never reaches main.js.
DMP_SHA256="7cead2c7cb3e4ff5c02e173cd6b81d22005e67c47ac2ce28e4b5c73d9ffcfdb2"
if [ "$(shasum -a 256 "$SRC/vendor/diff_match_patch.js" | cut -d" " -f1)" != "$DMP_SHA256" ]; then
  echo "vendor/diff_match_patch.js does not match the pinned SHA-256; refusing to build" >&2
  exit 1
fi
mkdir -p "$DIST"
{
  echo "'use strict';"
  echo "// MD Review plugin. Copyright 2026 Przemysław Lelakowski. Licensed under the Apache License 2.0;"
  echo "// it bundles diff-match-patch (Apache License 2.0). See LICENSE and NOTICE in the repository."
  echo "// Generated by build.sh from the sources - edit the sources, not this file."
  echo "const diff_match_patch = (function () { var module = { exports: {} };"
  cat "$SRC/vendor/diff_match_patch.js"
  echo "return module.exports; })();"
  cat "$SRC/core.js"
  cat "$SRC/plugin.js"
} > "$DIST/main.js"
cp "$SRC/manifest.json" "$SRC/styles.css" "$DIST/"
echo "built $DIST"
if [ $# -gt 0 ]; then
  VAULT="$(cd "$1" && pwd)"
  if [ ! -d "$VAULT/.obsidian" ]; then
    echo "not an Obsidian vault (no .obsidian folder): $VAULT" >&2
    exit 1
  fi
  OUT="$VAULT/.obsidian/plugins/md-review"
  mkdir -p "$OUT"
  cp "$DIST/main.js" "$DIST/manifest.json" "$DIST/styles.css" "$OUT/"
  echo "installed $OUT"
fi
